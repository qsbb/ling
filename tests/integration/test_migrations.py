"""迁移链冒烟测试：真正执行 Alembic，而不是 ``create_all``。

集成测试默认走 ``create_all_for_dev``，这意味着 ``migrations/versions`` 里的
脚本在生产 ``alembic upgrade head`` 之前从未被执行过。顺序写错、``down_revision``
断链、``op.execute`` 语法错误、模型与迁移漂移，都只有到部署时才暴露。

本文件覆盖四类检查：

a. 链完整性（纯静态，不需要数据库）：revision 唯一、down_revision 无悬空、
   单 head、从 root 到 head 拓扑有序且覆盖所有迁移文件；
b. 真实 upgrade：在临时数据库上 ``alembic upgrade head``，抽查关键表、
   关键偏索引与 ``alembic_version``；
c. downgrade 冒烟：最近两个迁移 downgrade 后再 upgrade 回 head；
d. ``alembic check``：断言没有未生成的迁移；若已知漂移仍在，动态 xfail 并写明原因。

隔离：每次测试会话 ``CREATE DATABASE ling_mig_<uuid>``，结束后 ``DROP``，
不会碰 ``ling_test``。整个文件只 upgrade 一次（session 级 fixture）。
"""

