@dataclass(frozen=True)
class Migration:
    revision: str
    down_revisions: tuple[str, ...]
    path: Path


@dataclass(frozen=True)
class MigrationChain:
    migrations: dict[str, Migration]
    order: tuple[str, ...]
    roots: tuple[str, ...]
    heads: tuple[str, ...]

    @property
    def head(self) -> str:
        assert len(self.heads) == 1, f"期望单 head，实际 {self.heads}"
        return self.heads[0]


def _normalize_down_revision(value: object, path: Path) -> tuple[str, ...]:
    if value is None:
        return ()
    if isinstance(value, str):
        return (value,)
    if isinstance(value, Sequence):
        items = tuple(value)
        if not all(isinstance(item, str) for item in items):
            raise AssertionError(f"{path.name} 的 down_revision 含非字符串项: {value!r}")
        return items
    raise AssertionError(f"{path.name} 的 down_revision 类型不合法: {value!r}")


@lru_cache(maxsize=1)
def _load_migrations() -> tuple[Migration, ...]:
    """导入每个迁移模块，读出 revision / down_revision。"""
    paths = sorted(
        path
        for path in VERSIONS_DIR.glob("*.py")
        if not path.name.startswith("._")  # 跳过 macOS AppleDouble
    )
    assert paths, f"在 {VERSIONS_DIR} 没有找到任何迁移文件"

    migrations: list[Migration] = []
    for path in paths:
        module_name = f"_ling_migration_{path.stem}"
        spec = importlib.util.spec_from_file_location(module_name, path)
        assert spec is not None and spec.loader is not None, f"无法加载 {path}"
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)

        revision = getattr(module, "revision", None)
        assert isinstance(revision, str) and revision, f"{path.name} 缺少字符串 revision"
        down_revisions = _normalize_down_revision(
            getattr(module, "down_revision", None), path
        )
        migrations.append(
            Migration(revision=revision, down_revisions=down_revisions, path=path)
        )
    return tuple(migrations)


def _by_revision() -> dict[str, Migration]:
    migrations = _load_migrations()
    counts = Counter(migration.revision for migration in migrations)
    duplicates = sorted(revision for revision, count in counts.items() if count > 1)
    assert not duplicates, f"revision 重复: {duplicates}"
    return {migration.revision: migration for migration in migrations}


@lru_cache(maxsize=1)
def _chain() -> MigrationChain:
    """用 Kahn 拓扑排序校验 DAG，并找出 root / head。

    悬空 down_revision 会让对应节点入度永远降不到 0，从而被当作环报出来；
    这里仍由 ``test_every_down_revision_exists`` 给出更直观的失败信息。
    """
    migrations = _by_revision()
    children: dict[str, list[str]] = {revision: [] for revision in migrations}
    in_degree: dict[str, int] = {
        revision: len(migration.down_revisions)
        for revision, migration in migrations.items()
    }
    for revision, migration in migrations.items():
        for parent in migration.down_revisions:
            if parent in children:
                children[parent].append(revision)

    roots = tuple(sorted(r for r, degree in in_degree.items() if degree == 0))
    queue = deque(roots)
    order: list[str] = []
    while queue:
        revision = queue.popleft()
        order.append(revision)
        for child in sorted(children[revision]):
            in_degree[child] -= 1
            if in_degree[child] == 0:
                queue.append(child)

    heads = tuple(sorted(r for r, kids in children.items() if not kids))
    return MigrationChain(
        migrations=migrations,
        order=tuple(order),
        roots=roots,
        heads=heads,
    )


def test_revision_ids_are_unique() -> None:
    revisions = [migration.revision for migration in _load_migrations()]
    duplicates = sorted(
        revision for revision, count in Counter(revisions).items() if count > 1
    )
    assert not duplicates, f"revision 重复: {duplicates}"


def test_every_down_revision_exists() -> None:
    migrations = _by_revision()
    dangling = [
        (migration.revision, parent)
        for migration in migrations.values()
        for parent in migration.down_revisions
        if parent not in migrations
    ]
    assert not dangling, f"down_revision 指向不存在的 revision: {dangling}"


def test_chain_has_single_root_and_single_head() -> None:
    chain = _chain()
    assert len(chain.roots) == 1, f"期望单 root，实际 {chain.roots}"
    assert len(chain.heads) == 1, f"期望单 head，实际 {chain.heads}"


def test_chain_is_topologically_walkable() -> None:
    chain = _chain()
    unresolved = sorted(set(chain.migrations) - set(chain.order))
    assert not unresolved, f"从 root 无法走到（存在环或断链）: {unresolved}"
    assert len(chain.order) == len(chain.migrations)
    assert chain.order[0] == chain.roots[0]
    assert chain.order[-1] == chain.heads[0]


