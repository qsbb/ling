async def _execute(url: str, statement: str) -> None:
    engine = create_async_engine(url, isolation_level="AUTOCOMMIT")
    try:
        async with engine.connect() as connection:
            await connection.execute(text(statement))
    finally:
        await engine.dispose()


async def _fetch(url: str, statement: str) -> list[tuple[object, ...]]:
    engine = create_async_engine(url)
    try:
        async with engine.connect() as connection:
            result = await connection.execute(text(statement))
            return [tuple(row) for row in result]
    finally:
        await engine.dispose()


def _database_url(base_url: str, database: str) -> str:
    return make_url(base_url).set(database=database).render_as_string(
        hide_password=False
    )


@contextmanager
def _database_url_env(url: str) -> Iterator[None]:
    """migrations/env.py 优先读 LING_DATABASE_URL；用完恢复，避免污染别的测试。"""
    previous = os.environ.get("LING_DATABASE_URL")
    os.environ["LING_DATABASE_URL"] = url
    try:
        yield
    finally:
        if previous is None:
            os.environ.pop("LING_DATABASE_URL", None)
        else:
            os.environ["LING_DATABASE_URL"] = previous


def _alembic_config(url: str) -> Config:
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    # 不依赖 pytest 的当前工作目录
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    config.set_main_option("prepend_sys_path", str(PROJECT_ROOT / "src"))
    config.set_main_option("path_separator", "os")
    config.set_main_option("sqlalchemy.url", url)
    return config


def _run_alembic(action: str, url: str, revision: str) -> None:
    config = _alembic_config(url)
    with _database_url_env(url):
        getattr(command, action)(config, revision)


